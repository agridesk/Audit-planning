import assert from 'node:assert/strict';
import {previewAuditorQualificationMigration20 as preview} from './auditor-scope-qualifications-migration-20.js';
const catalog=[['SlotKey','ScopeCode','DisplayName'],['SCOPE_01','ABC','ABC'],['SCOPE_09','NEW09','New 09'],['SCOPE_20','NEW20','New 20']];
const auditors=[['Auditor_UID','E-mail','ABC','NEW09','NEW20'],['uid-a','a@example.com','x','YES',''],['uid-b','b@example.com','','','true']];
const p=preview({auditors,catalog});
assert.equal(p.ok,true);
assert.equal(p.qualifiedCount,3);
assert.equal(p.writesPerformed,false);
assert.deepEqual(p.rows.map(r=>r.ScopeCode),['ABC','NEW09','NEW20']);
assert.equal(preview({auditors:auditors.map(r=>r.slice(0,4)),catalog}).ok,true,'Scope 20 is not expected to have a legacy source column');
assert.deepEqual(preview({auditors:auditors.map(r=>r.slice(0,4)),catalog}).unrepresentedScopes,['SCOPE_20']);
assert.deepEqual(preview({auditors:auditors.map(r=>r.slice(0,4)),catalog}).missingLegacyScopes,[]);
const missingLegacy=[['Auditor_UID','E-mail','NEW09','NEW20'],['uid-a','a@example.com','YES','']];
assert.equal(preview({auditors:missingLegacy,catalog}).ok,false,'Original scope 01 must have migration source');
assert.deepEqual(preview({auditors:missingLegacy,catalog}).missingLegacyScopes,['SCOPE_01']);
assert.equal(preview({auditors:[...auditors,['uid-a','different@example.com','x','','']],catalog}).ok,false);
assert.equal(preview({auditors:[...auditors,['uid-c','a@example.com','x','','']],catalog}).ok,false,'Duplicate email must fail closed');
assert.equal(preview({auditors,catalog:[...catalog,['SCOPE_09','ANOTHER','Another']]}).ok,false);
assert.equal(preview({auditors:[...auditors,['uid-c','c@example.com','maybe','','']],catalog}).ok,false);
const sharedColumnCatalog=[['SlotKey','ScopeCode','DisplayName'],['SCOPE_01','ABC','ABC'],['SCOPE_02','OTHER','ABC']];
assert.equal(preview({auditors,catalog:sharedColumnCatalog}).ok,false,'Two scopes cannot share one legacy qualification column');
assert.equal(preview({auditors,catalog:[catalog[0]]}).ok,false,'Empty scope catalog blocks migration');
console.log('auditor-scope-qualifications migration preview: read-only, fail-closed');
