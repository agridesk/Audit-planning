import assert from 'node:assert/strict';
import {planAuditorQualificationMigration20 as plan} from './auditor-scope-qualifications-migration-plan-20.js';
const catalog=[['ScopeCode','DisplayName','SlotKey'],['ABC','ABC','SCOPE_01'],['NEW','New scope','SCOPE_09']];
const auditors=[['E-mail','ABC','Auditor_UID'],['a@example.com','x','U1'],['b@example.com','','U2']];
const empty=[['Qualified','ScopeCode','Auditor_UID']];
let result=plan({auditors,catalog,relations:empty});
assert.equal(result.ok,true);
assert.equal(result.appendCount,1);
assert.equal(result.rowsToAppend[0].Auditor_UID,'U1');
assert.equal(result.rowsToAppend[0].ScopeCode,'ABC');
assert.equal(result.writesPerformed,false);
assert.equal(result.parity.ok,true);
result=plan({auditors,catalog,relations:[empty[0],['YES','ABC','U1']]});
assert.equal(result.ok,true);
assert.equal(result.appendCount,0);
assert.equal(result.alreadyPresentCount,1);
assert.equal(plan({auditors,catalog,relations:[empty[0],['YES','ABC','U2']]}).ok,false);
assert.equal(plan({auditors,catalog,relations:[empty[0],['NO','ABC','U1']]}).error,'EXISTING_RELATION_CONFLICT');
assert.equal(plan({auditors,catalog,relations:[empty[0],['YES','ABC','U1'],['YES','ABC','U1']]}).ok,false);
assert.equal(plan({auditors,catalog,relations:[empty[0],['YES','UNKNOWN','U1']]}).ok,false);
assert.equal(plan({auditors,catalog,relations:[]}).ok,false);
assert.equal(plan({auditors,catalog,relations:[['Qualified','ScopeCode','Auditor_UID',' qualified ']]}).error,'RELATION_SCHEMA_DUPLICATE_OR_EMPTY_HEADER');
assert.equal(plan({auditors,catalog,relations:[['Qualified','ScopeCode','Auditor_UID','']]}).ok,false);
const noLegacy=[['E-mail','Auditor_UID'],['a@example.com','U1']];
assert.equal(plan({auditors:noLegacy,catalog,relations:empty}).ok,false);
console.log('Scope20 qualification migration plan: safe append, parity, no writes');
