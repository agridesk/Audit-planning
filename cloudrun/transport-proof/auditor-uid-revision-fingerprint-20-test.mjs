import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {runInNewContext} from 'node:vm';
const code=readFileSync(new URL('./server-r4.js',import.meta.url),'utf8');
const start=code.indexOf('function directRowRevision('),end=code.indexOf('function directResolveAuditorEmail(',start);
assert.ok(start>=0&&end>start);
const norm=x=>String(x??'').trim().toLowerCase();
const col=(headers,names)=>headers.findIndex(h=>names.some(n=>norm(n)===norm(h)));
const val=(row,i)=>i>=0?String(row[i]??'').trim():'';
const context={createHash,col,val};
runInNewContext(code.slice(start,end),context);
const headers=['Audit ID','Status','Assigned to','Planning JSON','Last decision timestamp','Status since','Auditor_UID'];
const row=['AUD-1','Approved','someone@example.com','{}','2026-10-31','2026-10-31',''];
const originalFields=row.slice(0,6);
const legacy=createHash('sha256').update(originalFields.join('|')).digest('hex').slice(0,24);
assert.equal(context.directRowRevision(headers,row),legacy,'Missing UID must preserve existing revision contract');
const a=context.directRowRevision(headers,[...originalFields,'UID-A']);
const b=context.directRowRevision(headers,[...originalFields,'UID-B']);
assert.notEqual(a,b,'Reassignment by stable Auditor_UID must invalidate stale revisions');
assert.notEqual(a,legacy);
assert.equal(context.directRowRevision(headers,[...originalFields,'UID-A']),a,'Deterministic');
assert.ok(code.includes("g(['Status since'])].join('|')+(g(['Auditor_UID','Assigned_Auditor_UID'])?"),'Planning Toolkit revision must share canonical UID extension');
assert.ok(code.includes("val(row,css)].join('|')+(val(row,col(h,['Auditor_UID','Assigned_Auditor_UID']))?"),'Grid revision must share canonical UID extension');
console.log('Auditor UID revision fingerprint parity: legacy unchanged; owner UID change invalidates stale updates');
