import assert from 'node:assert/strict';
import {av20ResolveDay,av20CanPlan,av20ApplyAvailableOverride,av20Overlaps} from './availability-resolver-20.js';
const B=(state,start,end)=>({state,start,end});
assert.deepEqual(av20ResolveDay([]),[{start:0,end:1440,state:'FREE',provisionalConflict:false}]);
assert.equal(av20Overlaps(B('HARD',480,720),B('FREE',720,960)),false);
assert.equal(av20Overlaps(B('HARD',480,720),B('FREE',719,960)),true);
assert.equal(av20CanPlan([B('HARD',480,720)],720,960).allowed,true);
assert.equal(av20CanPlan([B('HARD',480,720)],719,960).allowed,false);
assert.equal(av20CanPlan([B('SOFT',480,720)],480,720).allowed,true);
assert.equal(av20CanPlan([B('PROVISIONAL',480,720)],480,720).allowed,false);
const overlap=av20ResolveDay([B('HARD',480,1080),B('COMMITTED',600,900)]);
assert.deepEqual(overlap.map(x=>[x.start,x.end,x.state]),[[0,480,'FREE'],[480,600,'HARD'],[600,900,'COMMITTED'],[900,1080,'HARD'],[1080,1440,'FREE']]);
const conflict=av20ResolveDay([B('HARD',480,720),B('PROVISIONAL',600,840)]);
assert.equal(conflict.find(x=>x.start===600).provisionalConflict,true);
assert.equal(conflict.find(x=>x.start===600).state,'HARD');
const available=av20ApplyAvailableOverride([B('SOFT',480,720),B('HARD',540,600),B('COMMITTED',900,960)],540,660);
assert.deepEqual(available.filter(x=>x.state==='SOFT').map(x=>[x.start,x.end]),[[480,540],[660,720]]);
assert.equal(available.some(x=>x.state==='HARD'),true);
assert.equal(available.some(x=>x.state==='COMMITTED'),true);
assert.throws(()=>av20ResolveDay([B('HARD',720,720)]),/AV20_INVALID_INTERVAL/);
console.log('AV20 resolver contracts: PASS');
