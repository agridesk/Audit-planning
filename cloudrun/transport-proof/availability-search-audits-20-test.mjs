import assert from 'node:assert/strict';
import {createPlanningOverlayService} from './availability-planning-overlay-service-20.js';
import {createAvailabilityHttpRouter} from './availability-http-api-20.js';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const headers=['Audit ID','Status','Assigned to','Planning JSON','Company'];
const row=(id,owner,date,company)=>[id,'Accepted',owner,JSON.stringify([{date,start:'09:00',end:'17:00'}]),company];
const rows=[headers,row('a1','a@example.com','2026-01-13','Test Orchid'),row('a2','a@example.com','2027-08-27','Test Orchids West'),row('b1','b@example.com','2026-04-17','Test Orchids Other')];
const auditors=[{auditorId:'a',email:'a@example.com'},{auditorId:'b',email:'b@example.com'}];
const storage={read:async()=>({blocks:[]}),mutate:async()=>({success:true})};
const svc=createPlanningOverlayService({service:storage,readPlanningRows:async()=>rows,listCanonicalAuditors:async()=>auditors});
const actor={id:'a',role:'auditor'};
const search=await svc.searchAudits({actor,auditorId:'a',term:'orchid'});
assert.deepEqual(search.results.map(x=>x.date),['2026-01-13','2027-08-27']);
assert.deepEqual(search.results.map(x=>x.company),['Test Orchid','Test Orchids West']);
assert.equal(search.truncated,false);
await assert.rejects(()=>svc.searchAudits({actor,auditorId:'b',term:'orchid'}),/NOT_AUTHORIZED/);
await assert.rejects(()=>svc.searchAudits({actor,auditorId:'a',term:'x'}),/INVALID_SEARCH_TERM/);
const router=createAvailabilityHttpRouter({service:svc,resolveIdentity:async()=>({auditorId:'a',role:'auditor'}),listAuditors:async()=>auditors});
async function http(url){
 let code,body;
 const res={writeHead:(c)=>{code=c},end:(s)=>{body=JSON.parse(s)}};
 await router({url,method:'GET',headers:{}},res);
 return{code,body};
}
let r=await http('/api/v1/availability/search-audits?auditorId=a&q=orchid');
assert.equal(r.code,200);
assert.equal(r.body.results.length,2);
r=await http('/api/v1/availability/search-audits?auditorId=b&q=orchid');
assert.equal(r.code,403);
r=await http('/api/v1/availability/search-audits?auditorId=a&q=x');
assert.equal(r.code,422);
const html=readFileSync(new URL('./availability-my-calendar-20.html',import.meta.url),'utf8');
assert(html.includes('id="auditSearch"'));
assert(html.includes('async function searchOwnAudits()'));
assert(html.includes('await goMonth(item.date.slice(0,7))'));
assert(html.includes('showDay(day)'));
assert(!html.includes('await selectDay(item.date)'),'Navigation may not toggle availability');
const script=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];assert(script);
new vm.Script(script);
console.log('PASS Fase 1.2 all-month own-audit search isolation, API, and nonmutating navigation');
