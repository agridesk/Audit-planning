/** AMS Availability 2.0 — canonical application service, Node.js ESM.
 * Storage adapter contract:
 *   read(auditorId) -> {version,baselineExceptions,baselineReleases,blocks,recurring,overrides,metadata} | null
 *   compareAndSwap(auditorId,expectedVersion,nextDocument) -> boolean (ATOMIC across instances)
 * Adapter must enforce durable storage and concurrency; no in-memory fallback in production.
 * Authorization is enforced here AND at the HTTP boundary.
 */
import {randomUUID} from 'node:crypto';
import {prepareAvailabilityMutation} from './availability-mutations-20.js';
import {resolveAvailabilityPeriod} from './availability-resolver-20.js';
import {buildManagerAvailabilityOverview} from './availability-manager-overview-20.js';
const clone=x=>structuredClone(x);
const str=x=>String(x??'').trim();
const initial=id=>({auditorId:id,version:0,baselineExceptions:[],baselineReleases:[],blocks:[],recurring:[{weekday:5,start:'00:00',end:'24:00'},{weekday:6,start:'00:00',end:'24:00'}],overrides:[],metadata:{changes:[],historyComplete:true,lastAvailabilityChangeAt:null,lastAvailabilityChangeBy:null,confirmation:null}});
function authorize(actor,id){const role=str(actor?.role).toLowerCase(),actorId=str(actor?.id);if(!actorId||!id||!(role==='manager'||role==='auditor'&&actorId===id))throw Error('NOT_AUTHORIZED');}
function validateAdapter(adapter){if(typeof adapter?.read!=='function'||typeof adapter?.compareAndSwap!=='function')throw Error('ATOMIC_STORAGE_ADAPTER_REQUIRED');}
export function createAvailabilityService(adapter){
 validateAdapter(adapter);
 async function read(actor,auditorId){const id=str(auditorId);authorize(actor,id);const doc=await adapter.read(id);if(doc!==null&&doc!==undefined&&(typeof doc!=='object'||Array.isArray(doc)))throw Error('CANONICAL_AVAILABILITY_DOCUMENT_INVALID');if(doc&&doc.auditorId!==id)throw Error('STORAGE_ID_MISMATCH');if(doc&&(!Number.isSafeInteger(doc.version)||doc.version<0||doc.version>=Number.MAX_SAFE_INTEGER||!Array.isArray(doc.blocks)||!Array.isArray(doc.baselineExceptions)||!Array.isArray(doc.baselineReleases)||!Array.isArray(doc.recurring)||!Array.isArray(doc.overrides)||!doc.metadata||typeof doc.metadata!=='object'||Array.isArray(doc.metadata)||!Array.isArray(doc.metadata.changes)))throw Error('CANONICAL_AVAILABILITY_DOCUMENT_INVALID');return clone(doc??initial(id));}
 async function mutate({actor,auditorId,expectedVersion,mutation,now=new Date().toISOString()}){
  const id=str(auditorId);authorize(actor,id);
  const current=await read(actor,id);
  if(current.planningLease)throw Error('PLANNING_LEASE_ACTIVE');
  const action=str(mutation?.action);
  // IDs are generated by server; do not trust caller-supplied IDs.
  const request=clone(mutation??{});
  if(['BLOCK_PERIOD','RELEASE_BASELINE','SET_FREE_OVERRIDE'].includes(action))request.id=randomUUID();
  const prepared=prepareAvailabilityMutation({actor,targetAuditorId:id,expectedVersion,mutation:request,snapshot:current,now});
  const next=clone(current);next.version=prepared.nextVersion;
  next.metadata??={};next.metadata.changes??=[];
  if(action==='BLOCK_PERIOD')next.baselineExceptions.push(prepared.payload);
  else if(action==='EDIT_HARD_BLOCK'){
   const at=next.baselineExceptions.findIndex(x=>str(x.id)===prepared.payload.id);
   if(at<0)throw Error('BASELINE_NOT_FOUND');
   next.baselineExceptions[at]=prepared.payload;
  }
  else if(action==='RELEASE_BASELINE'||action==='REMOVE_HARD_BLOCK')next.baselineReleases.push({...prepared.payload,id:prepared.payload.id||randomUUID()});
  else if(action==='SET_RECURRING')next.recurring=prepared.payload;
  else if(action==='SET_FREE_OVERRIDE')next.overrides.push(prepared.payload);
  else if(action==='CONFIRM_AVAILABILITY'){
   next.metadata.confirmation={confirmedAt:now,fromDate:prepared.payload.fromDate,throughDate:prepared.payload.toDate,availabilityVersion:next.version,confirmedBy:str(actor.id)};
  }
  if(action!=='CONFIRM_AVAILABILITY'){
   next.metadata.lastAvailabilityChangeAt=now;next.metadata.lastAvailabilityChangeBy=str(actor.id);
  }
  next.metadata.changes.push(prepared.audit);
  const success=await adapter.compareAndSwap(id,expectedVersion,next);
  if(success!==true)throw Error('VERSION_CONFLICT');
  return {auditorId:id,version:next.version,action,recordId:prepared.payload.id??(action==='REMOVE_HARD_BLOCK'?next.baselineReleases.at(-1)?.id:null)};
 }
 async function period({actor,auditorId,fromDate,toDate}){
  const doc=await read(actor,auditorId);
  return {auditorId:doc.auditorId,version:doc.version,days:resolveAvailabilityPeriod({fromDate,toDate,blocks:doc.blocks,recurring:doc.recurring,overrides:doc.overrides,baselineExceptions:doc.baselineExceptions,baselineReleases:doc.baselineReleases}),metadata:clone(doc.metadata)};
 }
 async function managerOverview({actor,auditorIds,fromDate,toDate,displayNames={}}){
  if(str(actor?.role).toLowerCase()!=='manager'||!str(actor?.id))throw Error('NOT_AUTHORIZED');
  if(!Array.isArray(auditorIds)||auditorIds.length>250||new Set(auditorIds).size!==auditorIds.length)throw Error('INVALID_AUDITOR_SET');
  const auditors=await Promise.all(auditorIds.map(async id=>{const d=await read(actor,id);return {auditorId:id,displayName:displayNames[id]??id,availability:d,metadata:{...d.metadata,availabilityVersion:d.version}};}));
  return buildManagerAvailabilityOverview({fromDate,toDate,auditors});
 }
 async function acquirePlanningLease({actor,auditorId,auditId,now=new Date().toISOString()}){
  const id=str(auditorId);authorize(actor,id);
  if(!str(auditId))throw Error('PLANNING_AUDIT_ID_REQUIRED');
  const current=await read(actor,id);
  if(current.planningLease)throw Error('PLANNING_LEASE_ACTIVE');
  if(current.version>=Number.MAX_SAFE_INTEGER-1)throw Error('VERSION_CONFLICT');
  const token=randomUUID(),next=clone(current);
  next.version=current.version+1;
  next.planningLease={token,auditId:str(auditId),acquiredAt:now,actorId:str(actor.id)};
  if(await adapter.compareAndSwap(id,current.version,next)!==true)throw Error('VERSION_CONFLICT');
  return {token,auditorId:id,auditId:str(auditId),version:next.version,document:next};
 }
 async function releasePlanningLease({actor,auditorId,token}){
  const id=str(auditorId);authorize(actor,id);
  const current=await read(actor,id);
  if(!token||current.planningLease?.token!==token)throw Error('PLANNING_LEASE_TOKEN_MISMATCH');
  if(current.version>=Number.MAX_SAFE_INTEGER-1)throw Error('VERSION_CONFLICT');
  const next=clone(current);next.version=current.version+1;next.planningLease=null;
  if(await adapter.compareAndSwap(id,current.version,next)!==true)throw Error('VERSION_CONFLICT');
  return {auditorId:id,version:next.version};
 }
 return Object.freeze({read,mutate,period,managerOverview,acquirePlanningLease,releasePlanningLease});
}