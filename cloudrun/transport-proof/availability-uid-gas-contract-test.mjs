import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const toolkit=readFileSync(new URL('../../Toolkit_AvailabilityMonth.js',import.meta.url),'utf8');
const availability=readFileSync(new URL('../../AvailabilityService.js',import.meta.url),'utf8');
assert.ok(toolkit.includes("return 'TOOLKIT_DIRECT_MONTH_UID|' + _mp_tdm_auditorUid_("),'Toolkit cache UID key');
assert.ok(toolkit.includes('function _mp_tdm_auditorUid_('),'Toolkit UID resolution');
assert.ok(availability.includes('function auditorUidForEmail_('),'Legacy bridge UID resolution');
assert.ok(availability.includes("var key = auditorUidForEmail_(auditorEmail) + '|'"),'Availability sheet identity UID');
const legacy=readFileSync(new URL('../../AuditorAvailabilityBackend.js',import.meta.url),'utf8');
assert.ok(legacy.includes("return 'AV_MONTH_UID|' + AV_uidForCurrentEmail_(auditorEmail)"),'Legacy monthly availability cache must be keyed by UID');
assert.ok(legacy.includes("function AV_uidForCurrentEmail_(auditorEmail)"),'Legacy UID lookup must exist');
assert.ok(!legacy.includes("return 'AV_MONTH|' + AV_normEmail_(auditorEmail)"),'Legacy mutable email cache prohibited');
const directory=readFileSync(new URL('../../AuditorsIndexService.js',import.meta.url),'utf8');
assert.ok(directory.includes('function AuditorsIndex_GetAuditorByUid(uid)'), 'Canonical auditor directory lookup by UID');
assert.ok(directory.includes("out.byUid[uid] = rec"),'Auditor directory keyed by UID');
assert.ok(directory.includes("out.byUid[uid] = out.byEmail[email]"),'Qualifications keyed by UID');
assert.ok(directory.includes("'directory:uid-v2'"),'UID schema cache isolation');
const rotation=readFileSync(new URL('../../RotationAuditorService.js',import.meta.url),'utf8');
assert.ok(rotation.includes('byUid: {}'),'Rotation auditor UID index');
assert.ok(rotation.includes('input.auditorUid || input.auditorEmail'),'Rotation UID input precedence');
assert.ok(rotation.includes("ROTATION_AUDITOR_IDENTITY_DUPLICATE"),'Rotation duplicate UID protection');
const auditorV5=readFileSync(new URL('../../AuditorV5Backend.js',import.meta.url),'utf8');
assert.ok(auditorV5.includes('AUD_V5_GRID_UID|'),'Auditor V5 cache UID keys');
assert.ok(auditorV5.includes('AUDIT_CACHE.getAuditorGrid(auditorV5_cacheAuditorUid_(email), view)'),'Central grid cache UID lookup');
assert.ok(auditorV5.includes('AUDIT_CACHE.removeAuditorGrid(auditorV5_cacheAuditorUid_(email))'),'Central grid cache UID invalidation');
assert.ok(directory.includes('var key = AuditorsIndex_clean_(email);'),'Qualification accepts exact Auditor UID without email normalization');
