import assert from 'node:assert/strict';
import {resolveCompanyScopeHours20 as resolve} from './company-scope-hours-resolver-20.js';
const base={companyId:'C1',scopeCode:'GAP',effectiveDate:'2027-01-01',companyScopes:[{Company_UID:'C1',ScopeCode:'GAP',Status:'ACTIVE'}],scopeVersions:[{ScopeCode:'GAP',VersionId:'V1',Hours_to_plan:'5',Status:'CURRENT'}],overrides:[]};
const run=patch=>resolve({...base,...patch});
assert.equal(run({}).formalHours,5);
const ov={OverrideId:'O1',Company_UID:'C1',ScopeCode:'GAP',Hours:'7',Status:'ACTIVE',Revision:'1'};
assert.equal(run({overrides:[ov]}).formalHours,7);
assert.equal(run({overrides:[ov]}).source,'COMPANY_OVERRIDE');
assert.equal(run({overrides:[ov],scopeVersions:[{...base.scopeVersions[0],VersionId:'V2',Hours_to_plan:'6'}]}).formalHours,7);
assert.equal(run({overrides:[{...ov,Hours:'8',Revision:'2'}]}).formalHours,8);
assert.equal(run({overrides:[{...ov,Status:'ENDED'}]}).formalHours,5);
assert.throws(()=>run({overrides:[ov,{...ov,OverrideId:'O2'}]}),/OVERLAPPING_COMPANY_OVERRIDES/);
assert.throws(()=>run({overrides:[{...ov,Hours:'bad'}]}),/INVALID_FORMAL_HOURS/);
assert.throws(()=>run({scopeVersions:[]}),/SCOPE_VERSION_MISSING/);
assert.throws(()=>run({companyScopes:[]}),/COMPANY_SCOPE_RELATION_MISSING/);
assert.throws(()=>run({overrides:null}),/HOURS_SOURCE_NOT_READY/);
assert.equal(run({overrides:[{...ov,EffectiveFrom:'2028-01-01'}]}).formalHours,5);
assert.throws(()=>run({scopeVersions:[{...base.scopeVersions[0],Effective_From:'2028-01-01'}]}),/SCOPE_VERSION_MISSING/);
assert.equal(run({scopeVersions:[{...base.scopeVersions[0],Effective_From:'2026-01-01',Effective_To:'2027-12-31'}]}).formalHours,5);
assert.throws(()=>run({scopeVersions:[{...base.scopeVersions[0],Effective_From:'2028-01-01',Effective_To:'2027-01-01'}]}),/SCOPE_VERSION_DATE_RANGE_INVALID/);
assert.throws(()=>run({scopeVersions:[{...base.scopeVersions[0],Status:'RETIRED',Effective_From:'2027-02-30'},base.scopeVersions[0]]}),/INVALID_EFFECTIVE_DATE/);
assert.throws(()=>run({scopeVersions:[base.scopeVersions[0],{...base.scopeVersions[0],VersionId:'V2'}]}),/SCOPE_VERSION_AMBIGUOUS/);
console.log('company-scope-hours-resolver-20: 14 checks passed');
