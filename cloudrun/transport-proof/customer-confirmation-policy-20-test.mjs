import assert from 'node:assert/strict';
import {evaluateCustomerResponse,evaluateFinalSlot,eligibleProposalReminders} from './customer-confirmation-policy-20.mjs';
const slot={date:'2026-11-18',start:'09:00',end:'12:00',location:'A'};
const proposal={visitId:'VIS-1',version:'V1',slot};
const response={type:'ACCEPT',visitId:'VIS-1',proposalVersion:'V1',channel:'CUSTOMER_LINK',actor:'CUSTOMER-1',timestamp:'2026-10-27T20:00:00Z'};
assert.equal(evaluateCustomerResponse(proposal,response).commitsPlanning,false);
assert.equal(evaluateFinalSlot(proposal,response,slot).allowed,true);
assert.equal(evaluateFinalSlot(proposal,response,{...slot,start:'08:00'}).code,'NEW_CUSTOMER_CONFIRMATION_REQUIRED');
assert.equal(evaluateFinalSlot(proposal,{...response,proposalVersion:'V0'},slot).code,'STALE_PROPOSAL');
assert.equal(evaluateFinalSlot(proposal,{...response,channel:''},slot).code,'RESPONSE_PROVENANCE_REQUIRED');
assert.equal(evaluateFinalSlot(proposal,{...response,type:'WINDOW_UNAVAILABLE'},slot).code,'CUSTOMER_CONFIRMATION_REQUIRED');
assert.equal(evaluateFinalSlot(proposal,{...response,type:'ALTERNATIVE',alternative:{...slot,date:'2026-11-19'}},slot).code,'CUSTOMER_CONFIRMATION_REQUIRED');
assert.equal(evaluateFinalSlot(proposal,null,slot,{confirmationRequired:false}).allowed,true);
const flex={allowedSlots:[slot],ranges:[{from:'2026-11-17',to:'2026-11-19',earliestStart:'08:00',latestFinish:'14:00',location:'A'}]};
const accepted={...response,type:'ACCEPT_WITH_FLEXIBILITY',flexibility:flex};
assert.equal(evaluateFinalSlot(proposal,accepted,{...slot,date:'2026-11-19',start:'10:00'}).allowed,true);
assert.equal(evaluateFinalSlot(proposal,accepted,{...slot,date:'2026-11-19',start:'13:00',end:'15:00'}).allowed,false);
assert.equal(evaluateFinalSlot(proposal,accepted,{...slot,location:'B'}).allowed,false);
assert.equal(evaluateCustomerResponse(proposal,{...accepted,flexibility:{allowedSlots:[],ranges:[]}}).code,'INVALID_FLEXIBILITY');
assert.equal(evaluateCustomerResponse(proposal,{...response,type:'ALTERNATIVE'}).code,'ALTERNATIVE_REQUIRED');
assert.deepEqual(eligibleProposalReminders([{id:1,sent:true},{id:2,sent:true,responseReceived:true},{id:3,sent:false},{id:4,sent:true,deadlinePassed:true}]).map(x=>x.id),[1]);
