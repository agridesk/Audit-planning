import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const root=new URL('../../',import.meta.url);
const read=p=>readFileSync(new URL(p,root),'utf8');
const run=read('scripts/ams-dev-enter-model-c-maintenance.ps1');
const rollback=read('scripts/ams-dev-restore-model-c-empty-target.ps1');
const gate=read('cloudrun/transport-proof/server-r15.js');
const build=read('cloudbuild.ams-transport-proof.yaml');
assert(run.includes("$project = 'audit-management-system-dev'"));
assert(run.includes("'ams-transport-proof'")&&run.includes("'ams-acceptance-20261107'"));
assert(run.includes("VerifyDEVSheetFreeze"),'must verify canonical DEV GAS System_Config guard');
assert(run.includes("'--clear-tags'"),'must remove old revision tag bypass URLs');
assert(run.includes("AMS_DEV_MAINTENANCE_MODE=true"));
assert(run.includes("AMS_DEV_MAINTENANCE_SOURCE_SHA=$sha"));
assert(run.includes("VerifyMaintenance $main $sha $image")&&run.includes("VerifyMaintenance $accept $sha $image"));
assert(run.includes("model-c-maintenance-state.json"),'must persist rollback state before traffic changes');
assert(run.includes("'--no-traffic'"),'must stage maintenance revisions before routing');
assert(run.includes("'--format=json'"),'must inspect actual GCloud state');
assert(!run.includes("'--allow-unauthenticated'"),'never open service IAM');
assert(!run.includes('audit-management-system-prod'),'do not target PROD');
assert(rollback.includes('RESTORE_DEV_WITH_EMPTY_MODEL_C_TARGET'));
assert(rollback.includes("ams_scope_extension_20_dev_"),'restoration must check target empty');
assert(rollback.includes("'--no-traffic'")&&!rollback.includes("'--tag=ams-restore'"),'restore nonmaintenance template must not expose legacy tagged bypass');
assert(rollback.includes("Remove-Item -LiteralPath $stateFile -Force"),'clear restore state only after verified rollback');
assert(gate.includes("process.env.AMS_RUNTIME_ENV==='DEV'&&process.env.AMS_DEV_MAINTENANCE_MODE==='true'"));
assert(build.includes('      - --no-traffic'),'build must never switch main route before gate is enabled');
console.log('PASS DEV maintenance and controlled rollback source checks, no PROD target');
