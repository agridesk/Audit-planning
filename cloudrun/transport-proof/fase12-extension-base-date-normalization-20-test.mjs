import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const backend=readFileSync(new URL('./server-r4.js',import.meta.url),'utf8');
const start=backend.indexOf('function extAddMonths(iso,n){');
const end=backend.indexOf('function extScopes(',start);
assert(start>=0&&end>start,'Legacy extension date boundary must exist');
const ctx={clean:x=>String(x??'').trim(),Date,Math,Number,String};
vm.runInNewContext(backend.slice(start,end),ctx);
const date=ctx.extAddMonths;
assert.equal(date('2026-08-28',0),'2026-08-28');
assert.equal(date('28/08/2026',0),'2026-08-28');
assert.equal(date('28/08/2026',4),'2026-12-28');
assert.equal(date('31/01/2027',1),'2027-02-28');
for(const invalid of ['31/02/2026','29/02/2025','2026-02-30','00/12/2026','13/13/2026','2026-00-15','','not-a-date'])assert.equal(date(invalid,0),'','Invalid date '+invalid+' must fail closed');
assert(backend.includes('EXTENSION_BASE_EXPIRY_MODEL_C_MISMATCH'));
assert(backend.includes('EXTENSION_UNDO_PROVENANCE_UNTRUSTED'));
assert(backend.includes('EXTENSION_MULTI_SCOPE_BLOCKED_PENDING_MODEL_C_SCOPE_SAFE_REMEDIATION_ISSUE_96'));
console.log('PASS extension original date equivalence and fail-closed writer guards');
