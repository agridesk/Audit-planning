import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const portal=readFileSync(new URL('./manager-portal.js',import.meta.url),'utf8');
const server=readFileSync(new URL('./server-r4.js',import.meta.url),'utf8');
const first=portal.indexOf('function extensionControls(r){');
const last=portal.indexOf('function grid4ScopeBadges(r){',first);
assert(first>=0&&last>first);
const sandbox={actorRole:'Manager',extensionAppliedState:r=>r.extensionApplied===true,esc:x=>String(x)};
vm.runInNewContext(portal.slice(first,last),sandbox);
const render=sandbox.extensionControls;
const pending={auditId:'A',statusKey:'PENDING_PLANNING',scopes:['MPS-GAP'],extensionMonths:4,canExtend:true};
assert.match(render(pending),/data-extension="apply"/,'one eligible scope: EXT');
assert.match(render({...pending,extensionApplied:true}),/data-extension="undo"/,'applied extension: Undo');
const multi={...pending,scopes:['MPS-GAP','GRASP'],eligibleExtensionScopes:['GRASP']};
assert.match(render(multi),/ext-manage/,'multiple eligible scopes: Manage Extensions');
assert.match(render({...multi,eligibleExtensionScopes:[]}),/ext-manage/,'multi-scope audit must retain direct navigation to its scope dossier even without currently eligible EXT');
assert.equal(render({...pending,extensionMonths:0,canExtend:false}),'' ,'single scope without extension: no button');
assert.equal(render({...multi,statusKey:'ACCEPTED'}),'' ,'non-Pending Planning: no extension action');
sandbox.actorRole='Auditor';
assert.equal(render(multi),'','Auditor cannot mutate extensions');
assert(portal.includes('querySelectorAll(".ext-act:not(.ext-manage)")'),'navigation cannot invoke legacy extension writer');
assert(portal.includes('auditId:row.auditId||""'),'navigation must pass selected Audit ID');
assert(portal.includes('visibleRecords=extTargetAuditId?data.records.filter'),'dossier must focus clicked audit');
assert(portal.includes('migration not verified'),'blocked per-scope actions must be explained');
assert(server.includes('eligibleExtensionScopes='),'manager read must expose per-scope eligibility');
assert(server.includes('extensionMonths:scopeExtensionMonths.get'),'dossier must expose per-scope extension months');
console.log('PASS four Extensions behaviors, scoped navigation, migration-safe read-only states');
