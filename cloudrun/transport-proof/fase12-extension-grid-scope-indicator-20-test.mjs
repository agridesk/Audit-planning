ctx.all.push(row);
let output=ctx.grid4ScopeBadges(row);
assert.match(output,/MPS-GAP.*?grid4-ext-dot/);
assert.equal((output.match(/grid4-ext-dot/g)||[]).length,1,'GRASP must not be implicitly extended');
ctx.updateExtendedScopeCodes20('A','GRASP',true);
output=ctx.grid4ScopeBadges(row);
assert.equal((output.match(/grid4-ext-dot/g)||[]).length,2,'independent scope markers');
ctx.updateExtendedScopeCodes20('A','MPS-GAP',false);
output=ctx.grid4ScopeBadges(row);
assert.equal((output.match(/grid4-ext-dot/g)||[]).length,1,'undo removes only its own marker');
assert(output.includes('GRASP')&&output.includes('grid4-ext-dot'));
assert(server.includes('function managerExtendedScopeCodes20(obValues,linkValues,scopeValues)'),'canonical bulk source');
assert(server.includes("val(row,ls).toUpperCase()!=='ACTIVE'"),'never mark inactive visit links');
assert(server.includes("['yes','true','1','x'].includes(flag)"),'only confirmed extension flags');
assert(server.includes('r.extendedScopeCodes=extendedScopes.get(clean(r.auditId))||[]'),'row projection');
assert(ui.includes("updateExtendedScopeCodes20(o.auditId,o.scopeCode,command==='apply')"),'multi scope immediate refresh');
assert(ui.includes("updateExtendedScopeCodes20(auditId,obligation.scopeCode,command==='apply')"),'single scope immediate refresh');
assert(!output.includes('+EXT'),'indicator must not consume badge width');
assert(output.includes('>E</span>'),'the same compact E emblem marks extended scope badges in single- and multi-scope rows');
const single={auditId:'S',scopes:['MPS-GAP'],extendedScopeCodes:['MPS-GAP']};
