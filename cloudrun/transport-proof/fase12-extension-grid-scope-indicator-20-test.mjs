import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const ui=fs.readFileSync(new URL('./manager-portal.js',import.meta.url),'utf8');
const server=fs.readFileSync(new URL('./server-r10.js',import.meta.url),'utf8');
const badgeStart=ui.indexOf('function grid4ScopeBadges(r){');
const badgeEnd=ui.indexOf('function renderOpenRow(r){',badgeStart);
