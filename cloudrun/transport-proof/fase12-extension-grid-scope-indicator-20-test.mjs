import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const ui=fs.readFileSync(new URL('./manager-portal.js',import.meta.url),'utf8');
const server=fs.readFileSync(new URL('./server-r10.js',import.meta.url),'utf8');
const badgeStart=ui.indexOf('function grid4ScopeBadges(r){');
const badgeEnd=ui.indexOf('function renderOpenRow(r){',badgeStart);
assert(badgeStart>=0&&badgeEnd>badgeStart,'grid scope badge renderer');
const code=ui.slice(badgeStart,badgeEnd);
const ctx={esc:x=>String(x),text:x=>String(x??''),all:[],mergeRowInPlace(auditId,patch){const row=ctx.all.find(r=>r.auditId===auditId);Object.assign(row,patch)}};
vm.runInNewContext(code,ctx);
const row={auditId:'A',scopes:['MPS-GAP','GRASP','MPS-ABC'],extendedScopeCodes:['MPS-GAP']};
ctx.all.push(row);
let output=ctx.grid4ScopeBadges(row);
assert.match(output,/MPS-GAP.*?\+EXT/);
assert(!/GRASP.*?\+EXT/.test(output),'GRASP must not be implicitly extended');
ctx.updateExtendedScopeCodes20('A','GRASP',true);
output=ctx.grid4ScopeBadges(row);
assert.equal((output.match(/\+EXT/g)||[]).length,2,'independent scope markers');
ctx.updateExtendedScopeCodes20('A','MPS-GAP',false);
output=ctx.grid4ScopeBadges(row);
assert.equal((output.match(/\+EXT/g)||[]).length,1,'undo removes only its own marker');
assert(output.includes('GRASP')&&output.includes('+EXT'));
assert(server.includes('function managerExtendedScopeCodes20(obValues,linkValues)'),'canonical bulk source');
assert(server.includes("val(row,ls).toUpperCase()!=='ACTIVE'"),'never mark inactive visit links');
assert(server.includes("['yes','true','1','x'].includes(flag)"),'only confirmed extension flags');
assert(server.includes('r.extendedScopeCodes=extendedScopes.get(clean(r.auditId))||[]'),'row projection');
assert(ui.includes("updateExtendedScopeCodes20(o.auditId,o.scopeCode,command==='apply')"),'multi scope immediate refresh');
assert(ui.includes("updateExtendedScopeCodes20(auditId,obligation.scopeCode,command==='apply')"),'single scope immediate refresh');
console.log('PASS scope-specific EXT badge, independent Undo and canonical active-link projection');
