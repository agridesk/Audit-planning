import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {resolveManagerApprovalRecipient20 as resolve} from './manager-approve-recipient-20.mjs';
const headers=['Auditor_UID','E-mail','Name'];
const rows=[headers,['uid-1','new@example.test','Auditor One'],['uid-2','other@example.test','Auditor Two']];
assert.equal(resolve({assigned:'old@example.test',assignedUid:'uid-1',auditorValues:rows}),'new@example.test');
assert.equal(resolve({assigned:'Auditor Two',auditorValues:rows}),'other@example.test');
assert.equal(resolve({assigned:'OTHER@EXAMPLE.TEST',auditorValues:rows}),'other@example.test');
assert.throws(()=>resolve({assigned:'old@example.test',auditorValues:rows}),/IDENTITY_NOT_UNIQUE_OR_MISSING/);
assert.throws(()=>resolve({assigned:'',auditorValues:rows}),/RECIPIENT_REQUIRED/);
assert.throws(()=>resolve({assignedUid:'missing',auditorValues:rows}),/UID_NOT_UNIQUE_OR_MISSING/);
assert.throws(()=>resolve({assignedUid:'uid-1',auditorValues:[headers,rows[1],rows[1]]}),/UID_NOT_UNIQUE_OR_MISSING/);
assert.throws(()=>resolve({assignedUid:'uid-1',auditorValues:[['E-mail','Name'],['a@example.test','Auditor One']]}),/IDENTITY_SCHEMA_MISSING/);
assert.throws(()=>resolve({assignedUid:'uid-1',auditorValues:[headers,['uid-1','invalid','Auditor One']]}),/RECIPIENT_REQUIRED/);
assert.throws(()=>resolve({assigned:'Auditor One',auditorValues:[headers,rows[1],['uid-3','third@example.test','Auditor One']]}),/IDENTITY_NOT_UNIQUE_OR_MISSING/);
const source=readFileSync(new URL('./server-r4.js',import.meta.url),'utf8');
const start=source.indexOf('async function directManagerApprove('),end=source.indexOf('let directAcceptSheetIdsCache20=',start);
assert.ok(start>=0&&end>start);
const handler=source.slice(start,end);
assert.match(source,/import \{resolveManagerApprovalRecipient20\} from '\.\/manager-approve-recipient-20\.mjs'/);
assert.match(handler,/resolveManagerApprovalRecipient20\(/);
assert.match(handler,/beforeKey!=='PENDING_APPROVAL'/);
assert.match(handler,/set\(\['Status'\],'Accepted'\)/);
assert.match(handler,/recipientEmail,resultStatus:'Accepted'/);
assert.ok(handler.indexOf('resolveManagerApprovalRecipient20(')<handler.indexOf("set(['Status'],'Accepted')"));
