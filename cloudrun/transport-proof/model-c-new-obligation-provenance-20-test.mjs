import assert from 'node:assert/strict';
import {buildNewModelCObligationWithHours20 as build} from './model-c-new-obligation-provenance-20.js';
const headers=['Obligation_ID','Company_UID','ScopeCode','Obligation_State','Formal_Hours','Formal_Hours_Source','Scope_Version_ID','Company_Hours_Override_ID','Company_Hours_Override_Revision','Hours_Resolved_At'];
const obligation={Obligation_ID:'OB-001',Company_UID:'C1',ScopeCode:'S-09',Obligation_State:'OPEN'};
const args={headers,obligation,companyId:'C1',scopeCode:'S-09',effectiveDate:'2026-10-31',now:'2026-10-31T13:00:00.000Z',companyScopes:[{Company_UID:'C1',ScopeCode:'S-09',Active:'YES'}],overrides:[],scopeVersions:[{ScopeCode:'S-09',Status:'CURRENT',VersionId:'V1',Hours_to_plan:'7.5'}]};
const base=build(args);
assert.equal(base.snapshot.Formal_Hours,7.5);
assert.equal(base.snapshot.Formal_Hours_Source,'SCOPE_DEFAULT');
assert.equal(base.snapshot.Scope_Version_ID,'V1');
assert.equal(base.row.length,headers.length);
assert.equal(base.row[headers.indexOf('Scope_Version_ID')],'V1');
assert.equal(obligation.Formal_Hours,undefined,'Input must remain unmodified');
const ov={OverrideId:'OV1',Company_UID:'C1',ScopeCode:'S-09',Hours:'5',Status:'ACTIVE',Revision:'R2'};
const overridden=build({...args,overrides:[ov]});
assert.equal(overridden.snapshot.Formal_Hours,5);
assert.equal(overridden.snapshot.Formal_Hours_Source,'COMPANY_OVERRIDE');
assert.equal(overridden.snapshot.Company_Hours_Override_ID,'OV1');
assert.equal(overridden.snapshot.Company_Hours_Override_Revision,'R2');
assert.throws(()=>build({...args,headers:headers.filter(h=>h!=='Scope_Version_ID')}),/OBLIGATION_HOURS_SCHEMA_MISSING/);
assert.throws(()=>build({...args,obligation:{...obligation,Company_UID:'OTHER'}}),/NEW_OBLIGATION_IDENTITY_MISMATCH/);
assert.throws(()=>build({...args,obligation:{...obligation,Obligation_State:'COMPLETED'}}),/NEW_OBLIGATION_STATE_INVALID/);
assert.throws(()=>build({...args,obligation:{...obligation,Formal_Hours:10}}),/NEW_OBLIGATION_HOURS_CONFLICT/);
assert.throws(()=>build({...args,obligation:{...obligation,Scope_Version_ID:'OLD'}}),/NEW_OBLIGATION_PROVENANCE_CONFLICT/);
assert.throws(()=>build({...args,overrides:[ov,{...ov,OverrideId:'OV2'}]}),/OVERLAPPING_COMPANY_OVERRIDES/);
assert.throws(()=>build({...args,scopeVersions:[]}),/SCOPE_VERSION_MISSING/);
assert.throws(()=>build({...args,companyScopes:[]}),/COMPANY_SCOPE_RELATION_MISSING/);
console.log('Model C new obligation provenance factory: baseline, override, schemas, identity, history and conflict gates passed');
