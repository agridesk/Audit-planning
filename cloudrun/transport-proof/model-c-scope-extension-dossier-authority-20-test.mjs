assert.equal(check([ctx],{cutoverVerified:false}).canMutate,false);
assert.equal(check([{...ctx,obligations:[ob('O1')]}]).canMutate,false);
assert.equal(check([{...ctx,obligations:[{...ob('O1'),pendingProjectionId:'TX'},ob('O2')]}]).canMutate,false);
assert.equal(check([{...ctx,companyUid:'OTHER'}]).canMutate,false);
assert.equal(check([{...ctx,obligations:[ob('O1',true),ob('O2')]}]).records[0].canUndo,true);
