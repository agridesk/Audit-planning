import assert from 'node:assert/strict';
import {stageScopeExtensionMigration20 as stage} from './model-c-scope-extension-staging-gate-20.mjs';
const context={auditId:'A',companyUid:'C',obligationIds:['O1','O2'],writerFenceVerified:false};
const doc=id=>({obligationId:id,auditId:'A',companyUid:'C'});
const plan={readOnly:true,seedPermitted:false,fatal:[{code:'OBLIGATION_LINEAGE_CONFLICT',auditId:'TEST_MULTIDAY_APPROVED_01',obligationId:'TEST_O1'},{code:'OBLIGATION_LINEAGE_CONFLICT',auditId:'TEST_MULTIDAY_APPROVED_01',obligationId:'TEST_O2'}],auditContexts:[context],documents:[doc('O1'),doc('O2')]};
const result=stage({plan,quarantineAuditIds:['TEST_MULTIDAY_APPROVED_01']});
assert.equal(result.eligibleForControlledStaging,true);
assert.equal(result.cutoverApproved,false);assert.equal(result.seedPermitted,false);
assert.equal(result.counts.contexts,1);assert.equal(result.counts.obligations,2);
assert.equal(result.counts.quarantinedAudits,1);
assert.equal(result.quarantinedAudits[0].reasons.length,2);
assert.throws(()=>stage({plan,quarantineAuditIds:['UNRELATED']}),/EXT_STAGE_QUARANTINE_WITHOUT_MATCHING_FAILURE/);
assert.throws(()=>stage({plan,quarantineAuditIds:['TEST_MULTIDAY_APPROVED_01','TEST_MULTIDAY_APPROVED_01']}),/EXT_STAGE_QUARANTINE_INVALID/);
assert.equal(stage({plan}).eligibleForControlledStaging,false);
const global={...plan,fatal:[...plan.fatal,{code:'SCHEMA_MISSING'}]};
assert.equal(stage({plan:global,quarantineAuditIds:['TEST_MULTIDAY_APPROVED_01']}).eligibleForControlledStaging,false);
const incorrect={...plan,documents:[doc('O1')]};
assert.throws(()=>stage({plan:incorrect,quarantineAuditIds:['TEST_MULTIDAY_APPROVED_01']}),/EXT_STAGE_CONTEXT_LINEAGE_MISMATCH/);
console.log('PASS Model C staging gate: explicit quarantine, no silent cutover, strict lineage');
