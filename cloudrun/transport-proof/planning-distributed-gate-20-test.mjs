import assert from 'node:assert/strict';
import {createPlanningDistributedGate} from './planning-distributed-gate-20.js';
const docs=new Map();
const adapter={async read(id){return structuredClone(docs.get(id)??null);},async compareAndSwap(id,expected,next){if((docs.get(id)?.version??0)!==expected)return false;docs.set(id,structuredClone(next));return true;}};
const a=createPlanningDistributedGate(adapter),b=createPlanningDistributedGate(adapter);
const req={operationId:'operation-a',actorId:'manager-a',kind:'PLANNING_DIRECT'};
const race=await Promise.allSettled([a.acquire(req),b.acquire({...req,operationId:'operation-b'})]);
assert.equal(race.filter(x=>x.status==='fulfilled').length,1);
assert.equal(race.filter(x=>x.status==='rejected').length,1);
const holder=(await a.read()).holder;
await assert.rejects(()=>a.acquire(req),/PLANNING_GATE_BUSY/);
await assert.rejects(()=>b.release({token:holder.token,verified:false,proof:'verified'}),/EVIDENCE_REQUIRED/);
await a.uncertain({token:holder.token,reason:'HTTP_TIMEOUT'});
await assert.rejects(()=>b.acquire({...req,operationId:'operation-c'}),/PLANNING_GATE_BUSY/);
await assert.rejects(()=>b.release({token:'wrong',verified:true,proof:'verified-result'}),/TOKEN_MISMATCH/);
await b.release({token:holder.token,verified:true,proof:'verified-sheets-commit'});
assert.equal((await a.read()).holder,null);
assert.equal((await b.acquire({...req,operationId:'operation-c'})).operationId,'operation-c');
console.log('Distributed planning gate: concurrent acquisitions, unknown outcome and proof-only recovery OK');
