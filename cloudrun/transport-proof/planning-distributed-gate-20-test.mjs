import assert from 'node:assert/strict';
import {createPlanningDistributedGate} from './planning-distributed-gate-20.js';
const docs=new Map();
const adapter={async read(id){assert.ok(!/^__.*__$/.test(id),'Firestore-reserved ID rejected');return structuredClone(docs.get(id)??null);},async compareAndSwap(id,expected,next){assert.ok(!/^__.*__$/.test(id),'Firestore-reserved ID rejected');if((docs.get(id)?.version??0)!==expected)return false;docs.set(id,structuredClone(next));return true;}};
const a=createPlanningDistributedGate(adapter),b=createPlanningDistributedGate(adapter);
const req={operationId:'operation-a',actorId:'manager-a',kind:'PLANNING_DIRECT'};
const race=await Promise.allSettled([a.acquire(req),b.acquire({...req,operationId:'operation-b'})]);
assert.equal(race.filter(x=>x.status==='fulfilled').length,1);
assert.equal(race.filter(x=>x.status==='rejected').length,1);
const holder=(await a.read()).holder;
await assert.rejects(()=>a.acquire(req),/PLANNING_GATE_BUSY/);
await assert.rejects(()=>b.release({token:holder.token,verified:false,proof:'verified'}),/EVIDENCE_REQUIRED/);
await a.uncertain({token:holder.token,reason:'HTTP_TIMEOUT'});
await assert.rejects(()=>b.acquire({...req,operationId:'operation-c'}),/PLANNING_GATE_BUSY/);
await assert.rejects(()=>b.release({token:'wrong',verified:true,proof:'verified-result'}),/TOKEN_MISMATCH/);
await b.release({token:holder.token,verified:true,proof:'verified-sheets-commit'});
assert.equal((await a.read()).holder,null);
assert.equal((await b.acquire({...req,operationId:'operation-c'})).operationId,'operation-c');
// A crashed ACTIVE owner is never unlocked based solely on elapsed age.
await assert.rejects(()=>a.quarantineOrphan({operationId:'operation-c',actorId:'manager-a',evidenceRef:'verified Cloud Run instance terminated 2026-10-29'}),/PLANNING_ORPHAN_TOO_RECENT/);
const stale=docs.get('planning-write-gate-v2');
stale.holder.acquiredAt=new Date(Date.now()-31*60*1000).toISOString();
docs.set('planning-write-gate-v2',stale);
await assert.rejects(()=>a.quarantineOrphan({operationId:'operation-c',actorId:'manager-a',evidenceRef:'short'}),/PLANNING_ORPHAN_ATTESTATION_REQUIRED/);
await assert.rejects(()=>a.quarantineOrphan({operationId:'wrong-operation',actorId:'manager-a',evidenceRef:'verified Cloud Run instance terminated 2026-10-29'}),/PLANNING_ORPHAN_GATE_MISMATCH/);
const quarantined=await a.quarantineOrphan({operationId:'operation-c',actorId:'manager-a',evidenceRef:'Cloud Run request ended; traceID-483782; independent operator checked logs'});
assert.equal(quarantined.state,'UNCERTAIN');
assert.ok(quarantined.uncertainAt);
assert.equal(quarantined.operatorAttestation.actorId,'manager-a');
await assert.rejects(()=>b.acquire({...req,operationId:'operation-d'}),/PLANNING_GATE_BUSY/);
// A quarantined holder can be claimed by exactly one forward recovery writer.
const recoveryDoc=docs.get('planning-write-gate-v2');
recoveryDoc.holder.uncertainAt=new Date(Date.now()-31*60*1000).toISOString();
docs.set('planning-write-gate-v2',recoveryDoc);
const recoveryClaim=await a.beginRecovery({operationId:'operation-c'});
assert.equal(recoveryClaim.state,'RECOVERING');
await assert.rejects(()=>b.beginRecovery({operationId:'operation-c'}),/NOT_QUARANTINED/);
await b.finishRecovery({operationId:'operation-c',token:recoveryClaim.token});
assert.equal((await a.read()).holder.state,'UNCERTAIN');
// Abandoned RECOVERING takeover requires isolation and rotates the fence token.
const abandoned=docs.get('planning-write-gate-v2');
abandoned.holder.state='RECOVERING';
abandoned.holder.recoveryStartedAt=new Date().toISOString();
docs.set('planning-write-gate-v2',abandoned);
await assert.rejects(()=>b.resumeRecovery({operationId:'operation-c'}),/QUARANTINE_ACTIVE/);
const aged=docs.get('planning-write-gate-v2');
aged.holder.recoveryStartedAt=new Date(Date.now()-31*60000).toISOString();
docs.set('planning-write-gate-v2',aged);
const priorToken=aged.holder.token;
const resumed=await b.resumeRecovery({operationId:'operation-c'});
assert.equal(resumed.state,'RECOVERING');
assert.notEqual(resumed.token,priorToken);
await assert.rejects(()=>a.finishRecovery({operationId:'operation-c',token:priorToken}),/FINISH_GATE_MISMATCH/);
await b.finishRecovery({operationId:'operation-c',token:resumed.token});
console.log('Distributed planning gate: concurrent acquisitions, unknown outcome and proof-only recovery OK');
