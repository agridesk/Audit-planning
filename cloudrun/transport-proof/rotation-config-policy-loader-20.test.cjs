'use strict';
const assert=require('node:assert/strict');
const {loadRotationPolicies20:load}=require('./rotation-config-policy-loader-20.cjs');
const h=['SlotKey','ScopeCode','Extension','Max number audits','Rotation_Normal_Maximum','Rotation_Applies','Rotation_Plus_One_Permitted'];
const rows=Array.from({length:8},(_,i)=>['SCOPE_0'+(i+1),'CODE_'+(i+1),'4','3','3','TRUE','FALSE']);
const result=load([h,...rows]);
assert.equal(result.length,8);
assert.equal(result[0].normalMaximum,3);
assert.equal(result[0].extensionPermitted,false);
assert.equal(result[0].scopeKey,'CODE_1');
assert.throws(()=>load([h,...rows.map((r,i)=>i===0?[...r.slice(0,4),'',...r.slice(5)]:r)]),/MAXIMUM_UNRESOLVED/);
assert.throws(()=>load([h,...rows.map((r,i)=>i===0?[...r.slice(0,5),'',r[6]]:r)]),/BOOLEAN_UNRESOLVED/);
assert.throws(()=>load([h,...rows.slice(1)]),/EIGHT_SCOPES_REQUIRED/);
assert.throws(()=>load([h,...rows,rows[0]]),/SCOPE_INVALID/);
assert.throws(()=>load([h,...rows.map((r,i)=>i===0?[r[0],r[1],r[2],r[3],'0',r[5],r[6]]:r)]),/MAXIMUM_UNRESOLVED/);
const exempt=rows.map((r,i)=>i===0?[...r.slice(0,4),'','FALSE','FALSE']:r);
assert.equal(load([h,...exempt])[0].rotationApplies,false);
assert.equal(load([h,...exempt])[0].normalMaximum,null);
assert.throws(()=>load([h,...exempt.map((r,i)=>i===0?[...r.slice(0,6),'TRUE']:r)]),/INCONSISTENT_EXEMPTION/);
console.log('Canonical policy loader: 12 checks passed');
