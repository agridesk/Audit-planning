import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {canonicalAssignment}=require('./rotation-direct-plan-gate-20.cjs');
const {scopeSlotsFromConfig20}=require('./rotation-config-scope-slots-20.cjs');
const {loadRotationPolicies20}=require('./rotation-config-policy-loader-20.cjs');
const {strictAmsCompletedHistory20}=require('./rotation-ams-strict-source-20.cjs');
const slots=Array.from({length:20},(_,i)=>'SCOPE_'+String(i+1).padStart(2,'0'));
const config=[['SlotKey','ScopeCode','Rotation_Normal_Maximum','Rotation_Applies','Rotation_Plus_One_Permitted'],...slots.map((s,i)=>[s,'CODE_'+(i+1),'3','true','false'])];
const mapping=scopeSlotsFromConfig20(config);
assert.equal(Object.keys(mapping).length,20);
assert.equal(loadRotationPolicies20(config).length,20);
const plan=[['Audit ID','Company_UID',...slots],['A-1','C-1',...slots.map((_,i)=>i===19?'X':'')]];
const auditors=[['Auditor_UID'],['uid-1']];
const assignment=canonicalAssignment({auditId:'A-1',auditorUid:'uid-1',planningValues:plan,auditorValues:auditors,scopeValues:config,logValues:[['Audit ID']]});
assert.deepEqual(assignment.scopeKeys,['CODE_20']);
const log=[['Audit ID','Company_UID','Auditor_UID','Status','Date completed',...slots],['A-0','C-1','uid-1','Completed','2026-01-02',...slots.map((_,i)=>i===19?'X':'')]];
assert.deepEqual(strictAmsCompletedHistory20(log,{scopeByColumn:mapping}).map(x=>x.scopeKey),['CODE_20']);
assert.throws(()=>scopeSlotsFromConfig20([...config,config[1]]),/ROTATION_CONFIG_SCOPE_MAPPING_INVALID/);
assert.throws(()=>canonicalAssignment({auditId:'A-1',auditorUid:'uid-1',planningValues:plan,auditorValues:auditors,scopeValues:[...config,config[1]],logValues:[['Audit ID']]}),/ROTATION_DIRECT_DUPLICATE_SCOPE_SLOT/);
console.log('rotation dynamic scope 01-20: PASS');
