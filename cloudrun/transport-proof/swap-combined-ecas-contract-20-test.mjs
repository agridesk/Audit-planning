import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const src=readFileSync(new URL('../../Swap20CombinedEcasContract.js',import.meta.url),'utf8');
let verified=[];
const ctx={String,JSON,Array,Error,ECAS20_VerifyPersistedCommunication_:(id,receipt,before)=>{
 verified.push([id,receipt,before.planningDigest]);return receipt==='receipt-'+id;
}};
runInNewContext(src,ctx);
const proposal={operationId:'swap-20261021-1',auditA:'A',auditB:'B',ecasComment:'Audit dates exchanged',blocksA:[{date:'2026-11-02',start:'09:00',end:'12:00'}],blocksB:[{date:'2026-11-03',start:'10:00',end:'14:00'}]};
const old=id=>({auditId:id,company:'Grower '+id,mpsNumber:'MPS-'+id,auditorName:'Auditor '+id,communicatedToEcas:true,communicationId:'receipt-'+id,planningDigest:'digest-'+id,blocks:[{date:'2026-10-01',start:'09:00',end:'12:00'}],scopes:['ABC']});
const a=old('A'),b=old('B');
const result=ctx.Swap20_buildCombinedEcasChange_(proposal,a,b);
assert.equal(result.ok,true);
assert.equal(result.queueAllowed,false);
assert.equal(result.payload.eventKey,'ECAS_AUDIT_CHANGED_DIGEST');
assert.equal(result.payload.auditChanges.length,2);
assert.equal(result.payload.lifecycle,'Accepted');
assert.equal(result.payload.auditId,proposal.operationId);
assert.equal(ctx.Swap20_verifyCombinedEcasProofs_(result.payload),true);
assert.equal(verified.length,2);
assert.equal(verified[0][0],'A');
assert.equal(verified[1][0],'B');
assert.equal(ctx.Swap20_buildCombinedEcasChange_(proposal,a,old('OTHER')).ok,false);
assert.equal(ctx.Swap20_buildCombinedEcasChange_(proposal,{...a,communicationId:''},b).ok,false);
assert.equal(ctx.Swap20_buildCombinedEcasChange_(proposal,a,{...b,planningDigest:''}).ok,false);
assert.equal(ctx.Swap20_buildCombinedEcasChange_({...proposal,ecasComment:''},a,b).ok,false);
assert.equal(ctx.Swap20_buildCombinedEcasChange_({...proposal,blocksA:a.blocks,blocksB:b.blocks},a,b).ok,false);
ctx.ECAS20_VerifyPersistedCommunication_=(id)=>id==='A';
assert.equal(ctx.Swap20_verifyCombinedEcasProofs_(result.payload),false);
assert.equal(ctx.Swap20_verifyCombinedEcasProofs_({...result.payload,auditChanges:[result.payload.auditChanges[0]]}),false);
console.log('SWAP combined ECAS payload and two independent provenance guards passed');
