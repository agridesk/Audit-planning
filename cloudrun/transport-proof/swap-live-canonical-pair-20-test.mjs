import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const source=readFileSync(new URL('../../PlanningRevisionTokenService.js',import.meta.url),'utf8');
for(const phase of ['headersRead','pairValidated'])assert.match(source,new RegExp("swapPairPhase\\('"+phase+"'\\)"));
assert.match(source,/swapPairPhase\(id===a\?'auditALocated':'auditBLocated'\)/);
assert.match(source,/swapPairPhase\(id===a\?'auditARowRead':'auditBRowRead'\)/);
const headers=['Audit ID','Status','Assigned to','Date - Planned','Planning JSON'];
const mk=(id,date)=>[id,'Accepted','paco@example.com',date,JSON.stringify({blocks:[{date,start:'09:00',end:'14:00'}]})];
const rows=[headers,mk('A','2026-10-30'),mk('B','2026-11-23')];
const sh={getLastColumn:()=>headers.length,getRange:(r,c,h,w)=>({getValues:()=>rows.slice(r-1,r-1+h).map(x=>x.slice(c-1,c-1+w))})};
const ctx={String,Array,JSON,Date,Number,Error,Utilities:{computeDigest:()=>[1,2,3],DigestAlgorithm:{SHA_1:'SHA_1'}},SpreadsheetApp:{getActiveSpreadsheet:()=>({getSheetByName:()=>sh})}};
runInNewContext(source,ctx);
ctx.PlanningRevisionTokenService_getMany=()=>({items:[{auditId:'A',revision:'STALE-A',snapshot:{status:'Accepted',assignedTo:'paco@example.com',planningJson:'{}'}},{auditId:'B',revision:'STALE-B',snapshot:{status:'Accepted',assignedTo:'paco@example.com',planningJson:'{}'}}]});
ctx.PRT_readCanonicalRow_=id=>({rowNumber:id==='A'?2:3,row:['STALE']});
const result=ctx.Swap20_readCanonicalPair({auditA:'A',auditB:'B'});
assert.equal(result.eligible,true);
assert.notEqual(result.auditA.revision,'STALE-A');
assert.equal(result.auditA.blocks[0].date,'2026-10-30');
assert.equal(result.auditB.blocks[0].date,'2026-11-23');
rows[1][0]='MOVED';
assert.throws(()=>ctx.Swap20_readCanonicalPair({auditA:'A',auditB:'B'}),/SWAP_CANONICAL_ROW_MOVED/);
console.log('SWAP live canonical pair token tests passed');
