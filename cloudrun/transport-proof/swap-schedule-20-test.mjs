import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const root=new URL('../../',import.meta.url);
const ctx={Error,String,Number,Array,Date,JSON,isNaN};
for(const name of ['Swap20OverlapRule.js','Swap20ProposalSchedule.js'])runInNewContext(readFileSync(new URL(name,root),'utf8'),ctx);
const b=(date,start,end)=>({date,start,end});
const pair=(a,c,ownerA='one@example.com',ownerB='two@example.com')=>({eligible:true,auditA:{blocks:a,assignedTo:ownerA},auditB:{blocks:c,assignedTo:ownerB}});
const result=ctx.Swap20_scheduleExchange_(pair([b('2026-10-21','09:00','11:00')],[b('2026-10-22','13:00','15:00')]));
assert.equal(result.blocksA[0].date,'2026-10-22');
assert.equal(result.blocksB[0].start,'09:00');
assert.equal(result.requiresAcknowledgement,true);
const timeOnly=ctx.Swap20_scheduleExchange_(pair([b('2026-10-21','09:00','11:00')],[b('2026-10-21','13:00','15:00')]));
assert.equal(timeOnly.requiresAcknowledgement,false);
assert.throws(()=>ctx.Swap20_scheduleExchange_(pair([b('2026-10-21','09:00','10:00')],[b('2026-10-22','09:00','11:00')])),/duration/);
assert.throws(()=>ctx.Swap20_scheduleExchange_(pair([b('2026-10-21','09:00','10:00')],[b('2026-10-22','09:00','10:00'),b('2026-10-23','09:00','10:00')])),/count/);
assert.throws(()=>ctx.Swap20_scheduleExchange_(pair([b('2026-02-30','09:00','10:00')],[b('2026-10-22','09:00','10:00')])),/date/);
assert.throws(()=>ctx.Swap20_scheduleExchange_(pair([b('2026-10-21','09:00','10:00')],[b('2026-10-21','09:00','10:00')])),/no schedule change/);
console.log('Swap schedule exchange tests passed');
